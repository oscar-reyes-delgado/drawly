import 'package:flutter/foundation.dart';

/// Minimal gettext-style localisation.
///
/// Call sites carry the Spanish and English text inline (`tr('Capas',
/// 'Layers')`); further languages are looked up from [_extra] keyed by the
/// English string, falling back to English.
class I18n extends ChangeNotifier {
  I18n._();
  static final I18n instance = I18n._();

  static const List<(String code, String name)> languages = [
    ('es', 'Español'),
    ('en', 'English'),
    ('pt', 'Português'),
    ('fr', 'Français'),
  ];

  String _lang = 'es';
  String get lang => _lang;

  set lang(String v) {
    if (v == _lang) return;
    _lang = languages.any((l) => l.$1 == v) ? v : 'en';
    notifyListeners();
  }

  void useSystemLocale(String languageCode) {
    lang = languages.any((l) => l.$1 == languageCode) ? languageCode : 'en';
  }
}

String tr(String es, String en) {
  final lang = I18n.instance.lang;
  if (lang == 'es') return es;
  if (lang == 'en') return en;
  return _extra[lang]?[en] ?? en;
}

